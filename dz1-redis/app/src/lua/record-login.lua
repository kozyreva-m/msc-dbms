-- Атомарно считает вход игрока.
-- KEYS[1]: ключ счётчика logins:{id}
-- ARGV[1]: TTL в секундах (86400 = 24 часа)
--
-- INCR и EXPIRE выполняются одним скриптом: между ними никто не вклинится,
-- поэтому не бывает счётчика без TTL, который никогда не сбросится.

local count = redis.call('INCR', KEYS[1])

-- TTL ставится только при первом входе: счётчик живёт 24 часа
-- с первого входа и потом сбрасывается целиком.
if count == 1 then
  redis.call('EXPIRE', KEYS[1], ARGV[1])
end

return count
